//! The readable engine folders of an output home, written by GenDB after every round of an
//! engine run (`engine::rounds`):
//!
//! ```text
//! engine/README.md              the run at a glance: every version's totals against the targets, the stop, the rounds
//! engine/versions/vNNN/         one version, complete: README.md, code/ (sources and proofs), code-view/, NOTES.md,
//!                               manifest.json, version.json, admission.json, evaluation.json, timing.json, totals.json, the official,
//!                               qualification and variant cells, variants.md, receipts.json
//! engine/rounds.md              one line per round: seed, outcome, status, provider-reported cost, session folder
//! ```
//!
//! The run directory's `engine/versions/vNNN/` is the source; this copy is replaced whole on every write, so a
//! version's `receipts.json`, added when its round closed, appears here too. Reading only: nothing here proves,
//! builds or measures.
//!
//! A general-line run (`engine.line: "general"`) writes its own layout ([`general`]): the version tree, the findings
//! log, versions and attempts of every branch, per-scale tables and the main-line head's profile.

pub mod general;

use super::{OutputError, io_error, write_text};
use serde_json::Value;
use std::fs;
use std::path::Path;

/// Write `<home>/engine/` from the run's engine directory `engine_dir`; returns what was written.
pub fn write_engine(home: &Path, engine_dir: &Path) -> Result<Value, OutputError> {
    let state = crate::engine::rounds::EngineState::read(engine_dir).map_err(|e| OutputError(e.to_string()))?;
    let out = home.join("engine");
    for version in &state.versions {
        let (Some(name), Some(source)) = (version["number"].as_u64(), version["directory"].as_str()) else { continue };
        let target = out.join("versions").join(format!("v{name:03}"));
        copy_tree(Path::new(source), &target)?;
    }
    write_text(&out.join("README.md"), &readme(&state))?;
    write_text(&out.join("rounds.md"), &rounds_page(&state))?;
    Ok(serde_json::json!({"engine":out,"versions":state.versions.len(),"rounds":state.rounds.len()}))
}

/// Copy `from` to `to` (replacing every file; files only).
fn copy_tree(from: &Path, to: &Path) -> Result<(), OutputError> {
    fs::create_dir_all(to).map_err(|e| io_error(to, e))?;
    for entry in fs::read_dir(from).map_err(|e| io_error(from, e))? {
        let entry = entry.map_err(|e| io_error(from, e))?;
        let path = entry.path();
        let target = to.join(entry.file_name());
        if path.is_dir() {
            copy_tree(&path, &target)?;
        } else if path.is_file() {
            if target.exists() {
                use std::os::unix::fs::PermissionsExt;
                let _ = fs::set_permissions(&target, fs::Permissions::from_mode(0o644));
            }
            fs::copy(&path, &target).map_err(|e| io_error(&target, e))?;
        }
    }
    Ok(())
}

fn ms(ns: &Value) -> String {
    ns.as_f64().map_or("-".to_string(), |ns| format!("{:.3}", ns / 1e6))
}

/// The run at a glance: per version its totals per worker count with the targets, and the stop.
fn readme(state: &crate::engine::rounds::EngineState) -> String {
    let mut out = String::from("# Schema engine\n\nOne verified engine for every supported query on the schema, built in rounds against the training templates. Totals are sums of the templates' official hot medians at the timing binding, in ms; the target at each worker count is the faster of the saved Umbra and DuckDB totals. Generated by GenDB after every round.\n\n");
    if state.versions.is_empty() {
        out.push_str("No version yet.\n");
    } else {
        out.push_str("| Version | Round | Workers | Engine ms | Target ms | Margin | Below both | Folder |\n|---|---:|---:|---:|---:|---:|---|---|\n");
        for v in &state.versions {
            let name = v["version"].as_str().unwrap_or("-");
            for w in v["totals"]["workers"].as_array().into_iter().flatten() {
                out.push_str(&format!("| {name} | {} | {} | {} | {} ({}) | {} | {} | [versions/v{:03}](versions/v{:03}/README.md) |\n", v["round"], w["workers"], ms(&w["engine_ns"]),
                    ms(&w["target_ns"]), w["target_engine"].as_str().unwrap_or("-"), w["margin"].as_f64().map_or("-".to_string(), |m| format!("{m:.3}x")),
                    if w["below_both"] == true { "yes" } else { "no" }, v["number"].as_u64().unwrap_or(0), v["number"].as_u64().unwrap_or(0)));
            }
        }
        if let Some(latest) = state.versions.last() {
            out.push_str(&format!("\nStop: {} ({}).\n", if latest["stop"]["stop"] == true { "met" } else { "not met" }, latest["version"].as_str().unwrap_or("-")));
        }
    }
    out.push_str(&format!("\nRounds: {} ([rounds.md](rounds.md)).\n", state.rounds.len()));
    out
}

/// One line per round.
fn rounds_page(state: &crate::engine::rounds::EngineState) -> String {
    let mut out = String::from("# Rounds\n\nEach round is one fresh author session ending with one submission: accepted as the next version, or recorded as an attempt (the next round then starts from the latest version). Costs are provider-reported, counted once per round.\n\n| Round | Seed | Outcome | Status | Cost USD | Session |\n|---:|---|---|---|---:|---|\n");
    for r in &state.rounds {
        let outcome = match r["outcome"].as_str() {
            Some("version") => format!("version {}", r["version"].as_str().unwrap_or("-")),
            Some(other) => other.to_string(),
            None => "-".to_string(),
        };
        out.push_str(&format!("| {} | {} | {outcome} | {} | {} | `{}` |\n", r["round"], r["seed"].as_str().unwrap_or("-"),
            r["status"].as_str().map_or_else(|| r["status"].to_string(), str::to_string), r["reported_cost_usd"].as_str().unwrap_or("-"), r["directory"].as_str().unwrap_or("-")));
    }
    out
}
