/// The id of version `number` (`v000`).
pub fn version_id(number: u64) -> String {
    format!("v{number:03}")
}

/// The number of version id `v012` (12); `None` for any other id.
pub fn version_number(id: &str) -> Option<u64> {
    id.strip_prefix('v')?.parse().ok()
}

/// The branch label of version 0 and of merges.
pub const MAIN: &str = "main";
/// The id of the root version (version 0, the framework's interpreter over the flat storage).
pub const ROOT_VERSION: &str = "v000";
/// The node record of a version or attempt folder.
pub const NODE_FILE: &str = "node.json";
/// The main-line changes, one JSON object per line.
pub const MAIN_LINE_FILE: &str = "main-line.jsonl";

/// How a node was made.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum NodeKind {
    /// The root of a run of one workload (no author, no parent in the run): version 0, generated by GenDB from the
    /// schema, or a continued run's seed version (`engine.seed_version`), copied by GenDB with its own storage uses.
    FrameworkGenerated,
    /// A submission of a branch session (one parent: the version its code derives from).
    Branch,
    /// A submission of a merge session (the main-line head and the branch head it took gains from).
    Merge,
    /// The root of a stage run (`engine::stage`, no author, no parent in the run): another run's accepted version (the
    /// seed) on every kept workload, and on the goal workload the seed when it verified out of the box, else version 0.
    StageSeed,
    /// The root of a run of several workloads (`engine.workloads`, no author, no parent in the run): one side per
    /// workload, each its seed's code, else the primary seed's code where it verified out of the box, else version 0.
    WorkloadSeed,
}

/// The per-workload records of a stage version, `versions/vNNN/workloads/<name>/` (`engine::stage`).
pub const WORKLOADS_DIRECTORY: &str = "workloads";
/// A stage version's record on one workload in that directory (`engine::stage::WorkloadRecord`).
pub const WORKLOAD_RECORD_FILE: &str = "workload.json";

/// What the tree reads of a stage version's record on one workload: its role (`goal` or `kept`; in a run of several
/// workloads `counted`, `check` or `kept`) and its recorded score at that workload's scale (`None` for a check workload,
/// which is never timed).
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct WorkloadScore {
    pub role: String,
    #[serde(default)]
    pub score: Option<RecordedScore>,
    /// A run of several workloads: the primary workload (its score is also the node's).
    #[serde(default)]
    pub primary: bool,
}

/// The role of a counted workload in a run of several workloads' records (`controller::request::MemberRole::Counted`).
const COUNTED: &str = "counted";
/// The role of a check workload there.
const CHECK: &str = "check";

/// A score as a node records it: at one scale, the score `(F, G)` (`engine::score`), out of how many
/// cells, and the timing record it was read from.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct RecordedScore {
    pub scale: String,
    pub score: Score,
    /// Every cell of the scale (templates x worker counts).
    pub cells: usize,
    /// Every cell finished and every total below both baselines' totals (the milestone "beats both", never a stop).
    pub beats_both: bool,
    pub record: PathBuf,
}

impl RecordedScore {
    /// The recorded form of a score at `scale` read from `record`.
    pub fn of(scale: &str, scored: &super::score::ScaleScore, record: &Path) -> Self {
        Self { scale: scale.to_string(), score: scored.score, cells: scored.cells_total, beats_both: scored.beats_both, record: record.to_path_buf() }
    }
}

impl RecordedScore {
    /// Every cell finished.
    pub fn all_finished(&self) -> bool {
        self.cells > 0 && self.score.finished == self.cells
    }

    /// Better at the same scale (`Score::is_better_than`). Recorded scores come from different timing windows, so this
    /// only decides whether a race is worth running; a race decides.
    pub fn better_than(&self, other: &RecordedScore) -> bool {
        self.scale == other.scale && self.score.is_better_than(&other.score)
    }
}

/// One node of the tree (`node.json`).
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct TreeNode {
    pub format_version: u32,
    /// `v003` or `b1-a004`.
    pub id: String,
    /// A version (true) or an attempt.
    pub accepted: bool,
    pub kind: NodeKind,
    /// `main` (version 0 and merges) or a branch (`b1`, ...).
    pub branch: String,
    /// The versions its code derives from (empty only for version 0).
    pub parents: Vec<String>,
    /// The scale it was judged at.
    pub scale: String,
    /// Its score there (`None`: refused before timing).
    pub score: Option<RecordedScore>,
    /// An attempt: why it was not accepted (the refusal, or the score comparison).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reason: Option<String>,
    /// The session and the iteration of its submission (`None` for version 0).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub session: Option<PathBuf>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub iteration: Option<u32>,
    /// The submission's stated direction and rationale.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub direction: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub rationale: Option<String>,
    pub created_unix_ms: u64,
}

impl TreeNode {
    /// The node's folder under `engine_dir`.
    pub fn directory(&self, engine_dir: &Path) -> PathBuf {
        node_directory(engine_dir, &self.id, self.accepted)
    }
}

/// The folder of node `id`: `versions/<id>` for a version, `attempts/<id>` for an attempt.
pub fn node_directory(engine_dir: &Path, id: &str, accepted: bool) -> PathBuf {
    engine_dir.join(if accepted { "versions" } else { "attempts" }).join(id)
}

/// A version's score at a later scale or in a later race (`versions/vNNN/scales/<scale>.json`).
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct LaterScore {
    pub format_version: u32,
    pub version: String,
    pub score: RecordedScore,
    /// Why it was timed (`scale_move`, `main_line_race`).
    pub reason: String,
    pub recorded_unix_ms: u64,
}

/// One change of the main-line head (`main-line.jsonl`).
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct MainLineChange {
    pub version: String,
    /// The version it replaced (`None` for version 0).
    pub previous: Option<String>,
    /// `version_0`, `race` (an interleaved timing against the previous head), `merge` (an accepted merge), `scale_move`.
    pub reason: String,
    /// The scale at which it was decided.
    pub scale: String,
    /// The interleaved timing that decided it.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub race: Option<PathBuf>,
    /// Set when that timing was not run for this decision but adopted: [`ADOPTED_ACCEPTANCE_RACE`] (the version's
    /// acceptance race, which timed it against this head, its parent, at the same scale and timing binding).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub adopted: Option<String>,
    /// The library's selection record.
    pub selection: gendb_artifacts::ContentId,
    pub at_unix_ms: u64,
}

/// [`MainLineChange::adopted`] of a decision taken from the accepted version's acceptance race (`race` names it).
pub const ADOPTED_ACCEPTANCE_RACE: &str = "acceptance_race";

/// Write `node` into its folder (`node.json`), once.
pub fn write_node(engine_dir: &Path, node: &TreeNode) -> Result<PathBuf, RecordError> {
    let dir = node.directory(engine_dir);
    records::create_dir(&dir)?;
    let path = dir.join(NODE_FILE);
    if path.is_file() {
        let existing: TreeNode = records::read_json(&path)?;
        if existing == *node {
            return Ok(path);
        }
        return Err(RecordError::new(&path, "a node record is written once"));
    }
    records::write_new_json(&path, node)?;
    Ok(path)
}

/// Record a version's score at a scale (`scales/<scale>.json`); a score already recorded there is kept.
pub fn record_scale_score(engine_dir: &Path, version: &str, score: &RecordedScore, reason: &str) -> Result<(), RecordError> {
    let dir = node_directory(engine_dir, version, true).join("scales");
    records::create_dir(&dir)?;
    let path = dir.join(format!("{}.json", score.scale));
    if path.is_file() {
        return Ok(());
    }
    records::write_new_json(&path, &LaterScore { format_version: 1, version: version.into(), score: score.clone(), reason: reason.into(), recorded_unix_ms: records::now_unix_ms() })
}

/// Append one main-line change (`main-line.jsonl`). The caller holds the run's main-line lock and has recorded the
/// library's selection first.
pub fn append_main_line(engine_dir: &Path, change: &MainLineChange) -> Result<(), RecordError> {
    let path = engine_dir.join(MAIN_LINE_FILE);
    append_line(&path, &serde_json::to_value(change).map_err(|e| RecordError::new(&path, e))?)
}

/// The findings log, one entry per line.
pub const FINDINGS_FILE: &str = "findings.jsonl";
/// The findings log as authors read it.
pub const FINDINGS_MARKDOWN: &str = "FINDINGS.md";
/// What the operator must review.
pub const FLAGS_FILE: &str = "flags.jsonl";

/// Append one JSON line to `path` (one `write` of the whole line, `O_APPEND`).
pub(crate) fn append_line(path: &Path, value: &Value) -> Result<(), RecordError> {
    let mut line = serde_json::to_vec(value).map_err(|e| RecordError::new(path, e))?;
    line.push(b'\n');
    fs::OpenOptions::new().create(true).append(true).open(path).and_then(|mut file| file.write_all(&line)).map_err(|e| RecordError::new(path, e))
}

/// Every line of a JSON-lines record (absent: none).
pub fn read_lines(path: &Path) -> Result<Vec<Value>, RecordError> {
    if !path.is_file() {
        return Ok(vec![]);
    }
    let text = fs::read_to_string(path).map_err(|e| RecordError::new(path, e))?;
    text.lines().filter(|l| !l.trim().is_empty()).map(|l| serde_json::from_str(l).map_err(|e| RecordError::new(path, e))).collect()
}

/// Append one finding (the node, its branch and parent, the change, the measured effect against the parent
/// and the author's findings) and rewrite `FINDINGS.md`, under the log's lock so concurrent sessions never leave a
/// stale view.
pub fn append_finding(engine_dir: &Path, entry: &Value) -> Result<(), RecordError> {
    records::create_dir(engine_dir)?;
    let lock_path = engine_dir.join("findings.lock");
    let file = fs::OpenOptions::new().create(true).truncate(false).write(true).open(&lock_path).map_err(|e| RecordError::new(&lock_path, e))?;
    let _lock = crate::file_lock::FileLock::acquire(file, libc::LOCK_EX).map_err(|e| RecordError::new(&lock_path, e))?;
    append_line(&engine_dir.join(FINDINGS_FILE), entry)?;
    let entries = read_lines(&engine_dir.join(FINDINGS_FILE))?;
    let path = engine_dir.join(FINDINGS_MARKDOWN);
    let staged = engine_dir.join(format!(".{FINDINGS_MARKDOWN}.{}", std::process::id()));
    fs::write(&staged, findings_markdown(&entries)).and_then(|()| fs::rename(&staged, &path)).map_err(|e| RecordError::new(&path, e))
}

/// `FINDINGS.md`: every entry, oldest first.
pub fn findings_markdown(entries: &[Value]) -> String {
    let text = |v: &Value| v.as_str().map_or_else(|| if v.is_null() { "-".to_string() } else { v.to_string() }, str::to_string);
    let mut out = String::from("# Findings\n\nWritten by GenDB after every evaluated submission (never by an author). Effect: finished cells F and normalized time G (lower is better) of the parent and the submission in one interleaved timing; per-cell ratios are the submission's median over the parent's.\n");
    for e in entries {
        out.push_str(&format!("\n## {} ({}, parent {}): {}\n\n", text(&e["node"]), text(&e["branch"]), text(&e["parent"]), if e["accepted"] == true { "accepted" } else { "not accepted" }));
        if !e["reason"].is_null() {
            out.push_str(&format!("- Why: {}\n", text(&e["reason"])));
        }
        out.push_str(&format!("- Change: {}\n", text(&e["change"]).lines().next().unwrap_or("-")));
        let effect = &e["effect"];
        if effect.is_object() {
            out.push_str(&format!("- Effect: F {} -> {}, G {} -> {}; cells faster {}, slower {}\n", text(&effect["parent_finished"]), text(&effect["finished"]),
                text(&effect["parent_normalized_time"]), text(&effect["normalized_time"]), text(&effect["cells_faster"]), text(&effect["cells_slower"])));
        }
        // A run of several workloads: the combined decision over the counted workloads.
        let combined = &e["combined"];
        if combined.is_object() {
            let summed = combined["workloads"].as_array().map_or_else(|| "-".to_string(), |w| w.iter().map(text).collect::<Vec<_>>().join(", "));
            // The first one-engine version accepted by the request's one-engine rule (`engine::stage::one_engine`).
            let decided = match (combined["better"] == true, combined[super::stage::one_engine::ONE_ENGINE_TRANSITION].is_object()) {
                (true, _) => "better",
                (false, true) => "not better; accepted as the first one-engine version: one_engine_transition",
                (false, false) => "not better",
            };
            out.push_str(&format!("- Combined over {summed}: F {} -> {}, G {} -> {} ({decided})\n", text(&combined["parent"]["score"]["finished"]), text(&combined["candidate"]["score"]["finished"]), text(&combined["parent"]["score"]["normalized_time"]),
                text(&combined["candidate"]["score"]["normalized_time"])));
        }
        // A stage run: each kept workload's measured effect (recorded, never deciding), or why it was not timed; a run
        // of several workloads: each other workload's effect (counted or kept) or its answers (check).
        for (name, other) in e["workloads"].as_object().into_iter().flatten() {
            let effect = &other["effect"];
            let role = match other["role"].as_str() {
                Some(COUNTED) => "Counted",
                Some(CHECK) => "Check",
                _ => "Kept",
            };
            let meaning = if role == "Counted" { "in the combined score" } else { "recorded, not deciding" };
            if effect.is_object() {
                out.push_str(&format!("- {role} {name} at {} ({meaning}): F {} -> {}, G {} -> {}; cells faster {}, slower {}\n", text(&other["scale"]),
                    text(&effect["parent_finished"]), text(&effect["finished"]), text(&effect["parent_normalized_time"]), text(&effect["normalized_time"]),
                    text(&effect["cells_faster"]), text(&effect["cells_slower"])));
            }
            let check = &other["check"];
            if check.is_object() {
                out.push_str(&format!("- Check {name} at {}: {} of {} answers agreed\n", text(&other["scale"]), text(&check["agreed"]), text(&check["calls"])));
            }
        }
        for kept in e["kept_workloads"].as_array().into_iter().flatten().filter(|k| k["status"] == "refused") {
            out.push_str(&format!("- Kept {} refused it: {}\n", text(&kept["name"]), text(&kept["reason"]).lines().next().unwrap_or("-")));
        }
        for member in e["members"].as_array().into_iter().flatten().filter(|m| m["status"] == "refused") {
            out.push_str(&format!("- Workload {} ({}) refused it at {}: {}\n", text(&member["name"]), text(&member["role"]), text(&member["step"]),
                text(&member["reason"]).lines().next().unwrap_or("-")));
        }
        for finding in e["findings"].as_array().into_iter().flatten() {
            out.push_str(&format!("- Finding: {}\n", text(finding)));
        }
    }
    out
}

/// Append one entry for the operator's review (`flags.jsonl`).
pub fn append_flag(engine_dir: &Path, entry: &Value) -> Result<(), RecordError> {
    records::create_dir(engine_dir)?;
    append_line(&engine_dir.join(FLAGS_FILE), entry)
}

/// Take the next attempt number of `label` (`b1`, or `main` for merge attempts) by creating its folder: returns the
/// attempt id (`b1-a001`) and its new folder. Concurrent sessions never take the same number.
pub fn take_attempt_directory(engine_dir: &Path, label: &str) -> Result<(String, PathBuf), RecordError> {
    let attempts = engine_dir.join("attempts");
    records::create_dir(&attempts)?;
    let taken = fs::read_dir(&attempts).map_err(|e| RecordError::new(&attempts, e))?.flatten().filter(|e| attempt_number(&e.file_name().to_string_lossy(), label).is_some()).count();
    for number in taken as u32 + 1.. {
        let id = format!("{label}-a{number:03}");
        let dir = attempts.join(&id);
        match fs::create_dir(&dir) {
            Ok(()) => return Ok((id, dir)),
            Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => continue,
            Err(error) => return Err(RecordError::new(&dir, error)),
        }
    }
    unreachable!("attempt numbers are unbounded")
}

/// The number of attempt folder `name` of `label` (`b1-a004` -> 4).
fn attempt_number(name: &str, label: &str) -> Option<u32> {
    name.strip_prefix(label)?.strip_prefix("-a")?.parse().ok()
}

/// The tree read from its records.
#[derive(Clone, Debug, Default)]
pub struct VersionTree {
    /// Versions in number order, then attempts in creation order.
    pub nodes: Vec<TreeNode>,
    /// Later scores: `(version, scale) -> score`.
    pub scale_scores: BTreeMap<(String, String), RecordedScore>,
    /// Main-line changes, oldest first.
    pub main_line: Vec<MainLineChange>,
    /// A stage run's scores per workload: `(version, workload) -> score` (empty in a run with one workload).
    pub workload_scores: BTreeMap<(String, String), WorkloadScore>,
}

impl VersionTree {
    /// Read every node, later score and main-line change under `engine_dir`.
    pub fn read(engine_dir: &Path) -> Result<Self, RecordError> {
        let mut tree = VersionTree::default();
        for (folder, accepted) in [("versions", true), ("attempts", false)] {
            let mut found: Vec<TreeNode> = vec![];
            for entry in children(&engine_dir.join(folder)) {
                let path = entry.join(NODE_FILE);
                if !path.is_file() {
                    continue;
                }
                let node: TreeNode = records::read_json(&path)?;
                if node.accepted != accepted {
                    return Err(RecordError::new(&path, "a node's folder disagrees with its accepted flag"));
                }
                for score in files(&entry.join("scales")) {
                    if score.extension().is_some_and(|x| x == "json") {
                        let recorded: LaterScore = records::read_json(&score)?;
                        tree.scale_scores.insert((recorded.version.clone(), recorded.score.scale.clone()), recorded.score);
                    }
                }
                for workload in children(&entry.join(WORKLOADS_DIRECTORY)) {
                    let path = workload.join(WORKLOAD_RECORD_FILE);
                    if accepted && path.is_file() {
                        let score: WorkloadScore = records::read_json(&path)?;
                        let name = workload.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
                        tree.workload_scores.insert((node.id.clone(), name), score);
                    }
                }
                found.push(node);
            }
            if accepted {
                found.sort_by_key(|n| (version_number(&n.id), n.id.clone()));
            } else {
                found.sort_by(|a, b| (a.created_unix_ms, &a.id).cmp(&(b.created_unix_ms, &b.id)));
            }
            tree.nodes.extend(found);
        }
        let main_line = engine_dir.join(MAIN_LINE_FILE);
        for line in read_lines(&main_line)? {
            tree.main_line.push(serde_json::from_value(line).map_err(|e| RecordError::new(&main_line, e))?);
        }
        Ok(tree)
    }

    /// The accepted versions, in number order.
    pub fn versions(&self) -> impl Iterator<Item = &TreeNode> {
        self.nodes.iter().filter(|n| n.accepted)
    }

    /// The attempts, in creation order.
    pub fn attempts(&self) -> impl Iterator<Item = &TreeNode> {
        self.nodes.iter().filter(|n| !n.accepted)
    }

    pub fn version(&self, id: &str) -> Option<&TreeNode> {
        self.versions().find(|n| n.id == id)
    }

    /// The main-line head (`None` before version 0 is recorded).
    pub fn main_line_head(&self) -> Option<&str> {
        self.main_line.last().map(|c| c.version.as_str())
    }

    /// The head of `branch`: its newest accepted version, else the root version (once recorded).
    pub fn branch_head(&self, branch: &str) -> Option<&str> {
        self.versions().filter(|n| n.branch == branch && n.kind != NodeKind::Merge).last().or_else(|| self.version(ROOT_VERSION)).map(|n| n.id.as_str())
    }

    /// The accepted versions and attempts of `branch` (a branch label; `main` lists version 0 and merges).
    pub fn of_branch<'a>(&'a self, branch: &'a str) -> impl Iterator<Item = &'a TreeNode> + 'a {
        self.nodes.iter().filter(move |n| n.branch == branch)
    }

    /// The recorded score of `version` on `workload` (a stage run's version; `None` elsewhere).
    pub fn workload_score(&self, version: &str, workload: &str) -> Option<&WorkloadScore> {
        self.workload_scores.get(&(version.to_string(), workload.to_string()))
    }

    /// Whether the run is a run of several workloads (`engine.workloads`): its records name a counted or check workload.
    pub fn is_run_of_several_workloads(&self) -> bool {
        self.workload_scores.values().any(|w| w.role == COUNTED || w.role == CHECK)
    }

    /// The combined score of `version` in a run of several workloads (`engine::score::CombinedScore`): the sums over its
    /// counted workloads' recorded scores, the primary first; `None` when it has no counted workload with a score.
    pub fn combined_score(&self, version: &str) -> Option<super::score::CombinedScore> {
        let mut counted: Vec<(&str, Score, usize, bool)> = self.workload_scores.iter().filter(|((v, _), w)| v == version && w.role == COUNTED)
            .filter_map(|((_, name), w)| w.score.as_ref().map(|s| (name.as_str(), s.score, s.cells, w.primary))).collect();
        if counted.is_empty() {
            return None;
        }
        counted.sort_by_key(|(_, _, _, primary)| !primary);
        super::score::CombinedScore::of(&counted.iter().map(|(n, s, c, _)| (*n, *s, *c)).collect::<Vec<_>>()).ok()
    }

    /// The score of `version` at `scale`: its own when it was judged there, else a later one.
    pub fn score_at(&self, version: &str, scale: &str) -> Option<RecordedScore> {
        let node = self.version(version)?;
        match &node.score {
            Some(score) if score.scale == scale => Some(score.clone()),
            _ => self.scale_scores.get(&(version.to_string(), scale.to_string())).cloned(),
        }
    }

    /// Every ancestor of `version` (itself included).
    pub fn ancestors(&self, version: &str) -> BTreeSet<String> {
        let mut seen = BTreeSet::new();
        let mut stack = vec![version.to_string()];
        while let Some(id) = stack.pop() {
            if !seen.insert(id.clone()) {
                continue;
            }
            if let Some(node) = self.version(&id) {
                stack.extend(node.parents.iter().cloned());
            }
        }
        seen
    }

    /// `ancestor` is `of` or one of its ancestors.
    pub fn is_ancestor(&self, ancestor: &str, of: &str) -> bool {
        self.ancestors(of).contains(ancestor)
    }

    /// The newest common ancestor of `a` and `b` (the highest-numbered version that is an ancestor of both).
    pub fn merge_base(&self, a: &str, b: &str) -> Option<String> {
        let common: BTreeSet<String> = self.ancestors(a).intersection(&self.ancestors(b)).cloned().collect();
        common.into_iter().max_by_key(|id| version_number(id))
    }

    /// `(branch head, main-line head)` when `branch` has accepted versions the main line has not taken: its head is not
    /// the main-line head and not one of its ancestors.
    pub fn merge_due(&self, branch: &str) -> Option<(String, String)> {
        let main = self.main_line_head()?;
        let head = self.branch_head(branch)?;
        let own = self.version(head).is_some_and(|n| n.branch == branch);
        (own && !self.is_ancestor(head, main)).then(|| (head.to_string(), main.to_string()))
    }

    /// The node of `id` (version or attempt).
    pub fn node(&self, id: &str) -> Option<&TreeNode> {
        self.nodes.iter().find(|n| n.id == id)
    }

    /// `tree.json`: every node with its folder, the later scores, the heads and the main-line changes.
    pub fn view(&self, engine_dir: &Path, branches: &[String]) -> Value {
        let heads: BTreeMap<&str, Option<&str>> = branches.iter().map(|b| (b.as_str(), self.branch_head(b))).collect();
        let mut view = json!({"format_version":1,"main_line_head":self.main_line_head(),"branch_heads":heads,
            "versions":self.versions().map(|n| json!({"node":n,"directory":n.directory(engine_dir)})).collect::<Vec<_>>(),
            "attempts":self.attempts().map(|n| json!({"node":n,"directory":n.directory(engine_dir)})).collect::<Vec<_>>(),
            "later_scores":self.scale_scores.iter().map(|((v, s), score)| json!({"version":v,"scale":s,"score":score})).collect::<Vec<_>>(),
            "main_line":self.main_line,
            "meaning":"versions passed admission and beat their parent in one interleaved timing; attempts were evaluated and not accepted (or refused); a branch's head is its newest version, the main-line head the newest main-line change (an interleaved timing or an accepted merge decided it)"});
        // A stage run: every version's score on every workload (a run with one workload keeps its view as before).
        if !self.workload_scores.is_empty() {
            view["workload_scores"] = json!(self.workload_scores.iter().map(|((v, w), s)| json!({"version":v,"workload":w,"role":s.role,"score":s.score})).collect::<Vec<_>>());
        }
        view
    }

    /// `TREE.md`: the heads, every version with its lineage and score, and every attempt with its reason.
    pub fn markdown(&self, branches: &[String]) -> String {
        let score = |s: &Option<RecordedScore>| s.as_ref().map_or("-".to_string(), |s| format!("{} {}/{} finished, G {}", s.scale, s.score.finished, s.cells, s.score.normalized_time));
        let mut out = format!("# Version tree\n\nMain-line head: {}. ", self.main_line_head().unwrap_or("none yet"));
        let heads: Vec<String> = branches.iter().map(|b| format!("{b} {}", self.branch_head(b).unwrap_or("-"))).collect();
        // A stage run shows every kept workload's recorded score beside the goal's (the goal's decided); a run of several
        // workloads the combined score and every other workload's score or check.
        let several = self.is_run_of_several_workloads();
        let staged = !several && self.workload_scores.values().any(|w| w.role != "goal");
        let (kept_header, kept_rule) = match (several, staged) {
            (true, _) => (" Combined (counted workloads) | Other workloads |", "---|---|"),
            (false, true) => (" Kept workloads (recorded, not deciding) |", "---|"),
            _ => ("", ""),
        };
        // The first one-engine version accepted by the request's one-engine rule did not beat its parent
        // (`engine::stage::one_engine`).
        let transition = super::stage::one_engine::ONE_ENGINE_TRANSITION;
        let beat = if self.main_line.iter().any(|c| c.reason == transition) {
            format!("Every version beat its parent in one interleaved timing, but the first one-engine version (main-line reason {transition}), which the request's one-engine rule accepted without beating it.")
        } else {
            "Every version beat its parent in one interleaved timing.".to_string()
        };
        out.push_str(&format!("Branch heads: {}.\n\nScore: F finished cells of all cells at the scale, then G (the sum over worker counts of the engine's total over the faster baseline's total; lower is better). {beat}\n\n## Versions\n\n| Version | Branch | Kind | Parents | Score | Direction |{kept_header}\n|---|---|---|---|---|---|{kept_rule}\n", heads.join(", ")));
        for n in self.versions() {
            let later: Vec<String> = self.scale_scores.iter().filter(|((v, _), _)| *v == n.id).map(|(_, s)| score(&Some(s.clone()))).collect();
            let shown = if later.is_empty() { score(&n.score) } else { format!("{}; later {}", score(&n.score), later.join("; ")) };
            let kept_cell = if several {
                let combined = self.combined_score(&n.id).map_or("-".to_string(), |c| format!("F {}/{}, G {}", c.score.finished, c.cells, c.score.normalized_time));
                let others: Vec<String> = self.workload_scores.iter().filter(|((v, _), w)| *v == n.id && !w.primary)
                    .map(|((_, name), w)| if w.role == CHECK { format!("{name} checked (check)") } else { format!("{name} {} ({})", score(&w.score), w.role) }).collect();
                format!(" {combined} | {} |", if others.is_empty() { "-".to_string() } else { others.join("; ") })
            } else if staged {
                let kept: Vec<String> = self.workload_scores.iter().filter(|((v, _), w)| *v == n.id && w.role != "goal").map(|((_, name), w)| format!("{name} {}", score(&w.score))).collect();
                format!(" {} |", if kept.is_empty() { "-".to_string() } else { kept.join("; ") })
            } else {
                String::new()
            };
            out.push_str(&format!("| {} | {} | {:?} | {} | {} | {} |{kept_cell}\n", n.id, n.branch, n.kind, n.parents.join(", "), shown, one_line(n.direction.as_deref())));
        }
        out.push_str("\n## Attempts\n\n| Attempt | Branch | Parent | Score | Why not accepted |\n|---|---|---|---|---|\n");
        for n in self.attempts() {
            out.push_str(&format!("| {} | {} | {} | {} | {} |\n", n.id, n.branch, n.parents.join(", "), score(&n.score), one_line(n.reason.as_deref())));
        }
        out.push_str("\n## Main-line changes\n\n");
        for c in &self.main_line {
            let after = c.previous.as_ref().map_or(String::new(), |p| format!(", after {p}"));
            let adopted = c.adopted.as_ref().map_or(String::new(), |a| format!("; timing adopted from its {}", a.replace('_', " ")));
            out.push_str(&format!("- {} ({}, at {}{after}{adopted})\n", c.version, c.reason, c.scale));
        }
        out
    }

    /// Rewrite `tree.json` and `TREE.md` under `engine_dir` from the records.
    pub fn write_views(&self, engine_dir: &Path, branches: &[String]) -> Result<(), RecordError> {
        records::write_json_atomic(&engine_dir.join("tree.json"), &self.view(engine_dir, branches))?;
        let path = engine_dir.join("TREE.md");
        let staged = engine_dir.join(format!(".TREE.md.{}", std::process::id()));
        fs::write(&staged, self.markdown(branches)).and_then(|()| fs::rename(&staged, &path)).map_err(|e| RecordError::new(&path, e))
    }
}

/// `text` on one table line (first line, `|` escaped), or `-`.
fn one_line(text: Option<&str>) -> String {
    text.and_then(|t| t.lines().next()).map_or("-".to_string(), |t| t.replace('|', "\\|"))
}

/// The subdirectories of `dir`, sorted.
fn children(dir: &Path) -> Vec<PathBuf> {
    let mut found: Vec<PathBuf> = fs::read_dir(dir).into_iter().flatten().flatten().map(|e| e.path()).filter(|p| p.is_dir()).collect();
    found.sort();
    found
}

/// The files of `dir`, sorted.
fn files(dir: &Path) -> Vec<PathBuf> {
    let mut found: Vec<PathBuf> = fs::read_dir(dir).into_iter().flatten().flatten().map(|e| e.path()).filter(|p| p.is_file()).collect();
    found.sort();
    found
}

