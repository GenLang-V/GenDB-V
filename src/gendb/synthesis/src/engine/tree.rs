//! The general line's version tree: every version (accepted) and attempt
//! (evaluated and not accepted, or refused) with its parents, branch and kind, the scale it was judged at and its score
//! there, and the heads: each branch's head and the main-line head.
//!
//! Records under `<run>/engine/` (every one written once; the views are rewritten from them):
//! - `versions/vNNN/node.json`: a version's node ([`TreeNode`], written with the version folder). Version numbers are
//!   global across branches: `vNNN` is the engine library's version `NNN + 1` (the library's first admitted version is
//!   `v000`, version 0), so the library's append-only stream allocates them;
//! - `versions/vNNN/scales/<scale>.json`: its score at a scale it was timed at later ([`LaterScore`]: a scale move or a
//!   race for the main-line head);
//! - `attempts/<label>-aNNN/node.json`: an attempt's node; the label is the branch (`b2-a017`) or `main` for a merge
//!   session's attempt. An attempt number is taken by creating its folder ([`take_attempt_directory`]);
//! - `main-line.jsonl`: every change of the main-line head ([`MainLineChange`]), mirroring the library's selection
//!   stream (`gendb_artifacts::verus::select_engine_version`);
//! - `tree.json` and `TREE.md`: the tree as authors and the operator read it ([`VersionTree::write_views`]);
//! - `findings.jsonl` and `FINDINGS.md`: the findings log, one entry per evaluated submission, written by
//!   the controller only ([`append_finding`]); authors read it and never write it;
//! - `flags.jsonl`: what the operator must look at (a wrong answer of a candidate, an incident of an admitted version;
//!   [`append_flag`]);
//! - in a stage run (`engine::stage`), `versions/vNNN/workloads/<name>/workload.json`: the version's record on each
//!   workload ([`WorkloadScore`] is what the tree reads of it: the role and the recorded score). `TREE.md` then shows
//!   every kept workload's score beside the goal's, and `FINDINGS.md` every kept workload's measured effect; a run
//!   without workloads writes both views as before. A run of several workloads (`engine.workloads`) keeps the same
//!   records with the roles `counted`, `check` and `kept` (a check workload's record has no score: it is never timed);
//!   `TREE.md` then shows the combined score (the sums over the counted workloads, `engine::score::CombinedScore`) and
//!   every other workload's score or check, and `FINDINGS.md` each workload's effect, check and refusal and the combined
//!   decision.
//!
//! Heads: a branch's head is its newest accepted version (every accepted version beat the branch head in one
//! interleaved timing, so the newest is the best), else the root version `v000`. The main-line head is the version the
//! newest main-line change names. A merge is due for a branch whose head is neither the main-line head nor one of its
//! ancestors ([`VersionTree::merge_due`]).

