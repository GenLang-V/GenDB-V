//! Generator of `stores/<name>/declaration.rs`: what a storage stores, from its declaration only.
//!
//! For every stored table `t{j}` (the declaration's tables, in order): its table id `stored_table_t{j}`, the ordinals
//! of its stored columns `stored_cols_t{j}` and their SQL columns `stored_columns_t{j}` with their declared nullability
//! (row-count carriers deliver the row count to the builder and are not stored columns). `stored_relations(db)` lists, per table, the stored
//! columns of `db`'s table in canonical row order: `proj_all(db.tables[stored_table_t{j}()], stored_cols_t{j}())`.
//! These are equalities with the database's own tables, with no value restriction; the storage entry proves the
//! stored parts represent them, and the query entry v4 quantifies over every database they are bound to.
//!
//! Lemmas: `lemma_declared_schema` (the declared columns are the schema's, by compute) and `lemma_stored_relations`
//! (on a well-formed database of the schema, each stored relation has its table's row count and lies in its declared
//! column domain). The file is shared byte for byte by the storage crate and every query crate that reads the storage,
//! so it names nothing of either (no source view, statement or builder).

use super::declared::DeclaredSource;
use super::source_module::{write_schema_lemma, write_table_declaration, TableNaming};
use super::storage_crate::StorageName;
use gendb_frontend::translator::comment_text;
use std::fmt::Write as _;

/// The names of `declaration.rs`.
const STORED_NAMING: TableNaming = TableNaming { prefix: "stored", schema_lemma: "lemma_declared_schema" };

const IMPORTS: &str = "use vstd::prelude::*;\n\
    use crate::spec::value::*;\n\
    use crate::spec::types::{Column, SqlType};\n\
    use crate::spec::typing::db_wf;\n\
    use crate::link::query::proj_all;\n\
    use crate::link::source::{cols_in_table, lemma_proj_all_index, lemma_source_in_domain, proj_columns, rows_in_columns};\n\
    use crate::schema::schema_spec;\n\nverus! {\n\n";

/// `declaration.rs` of storage `name` (checked by `DeclaredSource::check_deliverable` against `schema_widths`, the
/// column count of every table of the schema).
pub(super) fn declaration_module(name: &StorageName, declaration: &DeclaredSource, schema_widths: &[usize]) -> String {
    let mut o = String::new();
    write_header(&mut o, name, declaration);
    o.push_str(IMPORTS);
    for (j, t) in declaration.tables.iter().enumerate() {
        write_table_declaration(&mut o, &STORED_NAMING, j, t);
    }
    write_stored_relations(&mut o, declaration);
    write_schema_lemma(&mut o, declaration, schema_widths, &STORED_NAMING);
    write_relations_lemma(&mut o, declaration);
    o.push_str("} // verus!\n");
    o
}

fn write_header(o: &mut String, name: &StorageName, declaration: &DeclaredSource) {
    let _ = writeln!(o, "// FRAMEWORK FILE, GENERATED by gendb_verification::obligations from the declaration of storage `{name}`.");
    let _ = writeln!(o, "// Data only: which columns of which tables the storage stores, with their declared SQL types.");
    for (j, t) in declaration.tables.iter().enumerate() {
        let _ = writeln!(o, "// Stored table t{j} = {} (table id {}):", comment_text(&t.name), t.table_id);
        for c in &t.columns {
            let carrier = if c.row_count_only { ", only the builder's row count (not a stored column)" } else { "" };
            let nullable = if c.nullable { ", nullable" } else { "" };
            let _ = writeln!(o, "//   ordinal {} {}: {}{carrier}{nullable}.", c.ordinal, comment_text(&c.name), c.ty.sql_type());
        }
    }
}

/// `stored_relations(db)`: one relation per stored table.
fn write_stored_relations(o: &mut String, declaration: &DeclaredSource) {
    let relations: Vec<String> = (0..declaration.tables.len())
        .map(|j| format!("proj_all(db.tables[stored_table_t{j}() as int], stored_cols_t{j}())"))
        .collect();
    let _ = writeln!(
        o,
        "/// The stored relations of database `db`: per stored table, the stored columns of `db`'s table, row for row in\n\
         /// canonical row order.\npub open spec fn stored_relations(db: Database) -> Seq<Seq<Row>> {{\n    seq![{}]\n}}\n",
        relations.join(", ")
    );
}

/// `lemma_stored_relations`: row counts and declared column domains of the stored relations of a well-formed database.
fn write_relations_lemma(o: &mut String, declaration: &DeclaredSource) {
    o.push_str(
        "/// On a well-formed database of the schema, each stored relation has its table's row count and every value lies\n\
         /// in its declared column (`rows_in_columns`).\n\
         pub proof fn lemma_stored_relations(db: Database)\n    requires db.schema == schema_spec(), db_wf(db),\n    ensures\n",
    );
    let _ = writeln!(o, "        stored_relations(db).len() == {},", declaration.tables.len());
    for j in 0..declaration.tables.len() {
        let _ = writeln!(o, "        stored_relations(db)[{j}].len() == db.tables[stored_table_t{j}() as int].len(),");
        let _ = writeln!(o, "        rows_in_columns(stored_relations(db)[{j}], stored_columns_t{j}()),");
    }
    o.push_str("{\n    lemma_declared_schema();\n");
    for j in 0..declaration.tables.len() {
        let _ = writeln!(o, "    lemma_source_in_domain(db, stored_table_t{j}(), stored_cols_t{j}());");
        let _ = writeln!(o, "    lemma_proj_all_index(db.tables[stored_table_t{j}() as int], stored_cols_t{j}());");
    }
    o.push_str("}\n\n");
}
