//! Generators of the whole-schema files: for a storage that stores every column
//! of every table of the schema, in table and column order ([`whole_schema_declaration`]; the instance of a storage
//! family is one), so that its builder over `crate::sources_flat` and an opener over the store are written by table id
//! for any table count.
//!
//! - `whole_schema.rs` (`crate::whole_schema`), in a storage crate built from admitted storages whose own declaration is
//!   whole-schema, and in an engine crate that reads such a storage (one that is not a generated flat storage): per
//!   whole-schema store `<s>` of the crate, `lemma_<s>(db)`: on a well-formed database of the schema,
//!   `crate::stores::<s>::declaration::stored_relations(db) == db.tables`, table for table.
//! - `schema_exec.rs` (`crate::schema_exec`), in such a storage crate only: the column schema as executable data
//!   (`schema_exec()`, proved equal to `schema_spec()`), the text engine crates carry as `gendb_entry/schema_exec.rs`
//!   (here a crate-root module: the fixed derived storage entry declares its own submodules and stays byte for byte), so
//!   a builder reads each column's type and nullability at run time.
//!
//! Both are crate-root modules, declared by the generated crate root, covered by no shared definition of
//! `gendb_registry` (so in no storage's closure), and generated only for such crates: every other storage and engine
//! crate assembles byte for byte as before (unit tests with golden digests).
//!
//! Trust: none. The text is generated from the schema and the declarations only and is checked by Verus with
//! `--no-cheating` in the crate it belongs to, so a wrong generation fails verification.

use super::crate_files::file;
use super::declared::DeclaredSource;
use super::storage_crate::StorageName;
use crate::verus::FrameworkSource;
use gendb_frontend::ast::TableDef;
use gendb_frontend::translator::{comment_text, sql_type};
use std::fmt::Write as _;

/// Identity of this generator, named in the generated modules' headers.
pub const WHOLE_SCHEMA_GENERATOR: &str = "gendb-whole-schema-v1";
/// The path of the whole-schema module, relative to `src/` (module `crate::whole_schema`).
pub const WHOLE_SCHEMA_PATH: &str = "whole_schema.rs";
/// The path of a storage crate's executable schema, relative to `src/` (module `crate::schema_exec`).
pub const STORAGE_SCHEMA_EXEC_PATH: &str = "schema_exec.rs";

/// Whether `declaration` stores every column of every table of `schema`: one declared table per schema table, in table
/// order, each with every column in column order (none a row-count carrier).
pub fn whole_schema_declaration(schema: &[TableDef], declaration: &DeclaredSource) -> bool {
    declaration.tables.len() == schema.len()
        && declaration.tables.iter().zip(schema).enumerate().all(|(j, (declared, table))| {
            declared.table_id == j
                && declared.columns.len() == table.columns.len()
                && declared.columns.iter().enumerate().all(|(k, c)| c.ordinal == k && !c.row_count_only)
        })
}

/// `whole_schema.rs` over `schema` for the whole-schema stores `stores` of the crate (at least one), in their order.
pub(super) fn whole_schema_file(schema: &[TableDef], stores: &[&StorageName]) -> FrameworkSource {
    let mut o = String::new();
    let _ = writeln!(o, "// FRAMEWORK FILE, GENERATED by gendb_verification::obligations ({WHOLE_SCHEMA_GENERATOR}): the stored relations of");
    o.push_str("// this crate's stores that store every column of every table, by table id. Data only (the schema and the stores'\n");
    o.push_str("// declarations); checked by Verus with the crate, so a wrong generation fails verification.\n");
    for (j, t) in schema.iter().enumerate() {
        let _ = writeln!(o, "// Table {j} = `{}` ({} columns).", comment_text(&t.name), t.columns.len());
    }
    for s in stores {
        let _ = writeln!(o, "// Whole-schema store `{s}`: lemma_{s}.");
    }
    let _ = write!(
        o,
        "use vstd::prelude::*;\nuse crate::spec::value::{{Database, Row}};\nuse crate::spec::typing::{{db_wf, row_in_table}};\n\
         use crate::spec::types::SqlType;\nuse crate::schema::schema_spec;\nuse crate::link::query::proj_all;\nuse crate::link::source::lemma_proj_all_index;\n\n\
         verus! {{\n\n/// The number of tables of the schema (table ids `0..TABLE_COUNT`, in `schema_spec()` order).\npub const TABLE_COUNT: usize = {};\n\n",
        schema.len()
    );
    o.push_str(PROJ_IDENTITY);
    write_shape_lemma(&mut o, schema);
    for s in stores {
        write_store_lemma(&mut o, schema, s);
    }
    o.push_str("} // verus!\n");
    file(WHOLE_SCHEMA_PATH, o)
}

/// A relation is its own projection onto all of its columns in order (the flat access modules' helper).
const PROJ_IDENTITY: &str = r#"/// A relation whose rows have `n` columns is its own projection onto columns `0..n`.
proof fn lemma_proj_identity(rows: Seq<Row>, cols: Seq<nat>, n: nat)
    requires
        cols.len() == n,
        forall|k: int| 0 <= k < n ==> #[trigger] cols[k] == k,
        forall|i: int| 0 <= i < rows.len() ==> #[trigger] rows[i].len() == n,
    ensures
        proj_all(rows, cols) == rows,
{
    lemma_proj_all_index(rows, cols);
    assert forall|i: int| 0 <= i < rows.len() implies #[trigger] proj_all(rows, cols)[i] == rows[i] by {
        assert(proj_all(rows, cols)[i] =~= rows[i]);
    }
    assert(proj_all(rows, cols) =~= rows);
}

"#;

/// `stored_type` and `lemma_schema_shape`: the schema has `TABLE_COUNT` tables, each with a column, every column of a
/// stored type (each fact by compute, then for every table and column id by a case split).
fn write_shape_lemma(o: &mut String, schema: &[TableDef]) {
    o.push_str(
        "/// Whether a column type is one a storage stores (every type but `boolean` and `timestamp`).\n\
         pub open spec fn stored_type(ty: SqlType) -> bool {\n    ty is Int4 || ty is Int8 || ty is Numeric || ty is Date || ty is Text || ty is Varchar || ty is Bpchar\n}\n\n\
         /// The schema's shape: `TABLE_COUNT` tables, each with at least one column, every column of a stored type.\n\
         pub proof fn lemma_schema_shape()\n    ensures\n        schema_spec().len() == TABLE_COUNT,\n        \
         forall|t: int| 0 <= t < TABLE_COUNT ==> #[trigger] schema_spec()[t].columns.len() >= 1,\n        \
         forall|t: int, c: int| 0 <= t < TABLE_COUNT && 0 <= c < schema_spec()[t].columns.len() ==> stored_type(#[trigger] schema_spec()[t].columns[c].ty),\n{\n",
    );
    let _ = writeln!(o, "    assert(schema_spec().len() == {}) by (compute);", schema.len());
    for (j, t) in schema.iter().enumerate() {
        let _ = writeln!(o, "    assert(schema_spec()[{j}].columns.len() == {}) by (compute);", t.columns.len());
        for (k, c) in t.columns.iter().enumerate() {
            let _ = writeln!(o, "    assert(schema_spec()[{j}].columns[{k}].ty == ({})) by (compute);", sql_type(&c.ty));
        }
    }
    let tables: String = (0..schema.len()).map(|j| format!("{}if t == {j} {{}}", if j == 0 { "" } else { " else " })).collect();
    let _ = writeln!(o, "    assert forall|t: int| 0 <= t < TABLE_COUNT implies #[trigger] schema_spec()[t].columns.len() >= 1 by {{\n        {tables}\n    }}");
    let columns: String = schema
        .iter()
        .enumerate()
        .map(|(j, t)| {
            let split: String = (0..t.columns.len()).map(|k| format!("{}if c == {k} {{}}", if k == 0 { "" } else { " else " })).collect();
            format!("{}if t == {j} {{ {split} }}", if j == 0 { "" } else { " else " })
        })
        .collect();
    let _ = writeln!(
        o,
        "    assert forall|t: int, c: int| 0 <= t < TABLE_COUNT && 0 <= c < schema_spec()[t].columns.len() implies stored_type(#[trigger] schema_spec()[t].columns[c].ty) by {{\n        {columns}\n    }}\n}}\n"
    );
}

/// `lemma_<s>`: store `s`'s stored relations are the database's tables (each table's relation is its projection onto
/// every column, in order).
fn write_store_lemma(o: &mut String, schema: &[TableDef], s: &StorageName) {
    let d = format!("crate::stores::{s}::declaration");
    let _ = write!(
        o,
        "/// The stored relations of store `{s}` are `db`'s tables, table for table (it stores every column of every table, in\n\
         /// order).\npub proof fn lemma_{s}(db: Database)\n    requires\n        db.schema == schema_spec(),\n        db_wf(db),\n    \
         ensures\n        {d}::stored_relations(db) == db.tables,\n{{\n    {d}::lemma_declared_schema();\n"
    );
    for (j, t) in schema.iter().enumerate() {
        let n = t.columns.len();
        let split: String = (0..n).map(|k| format!("{}if k == {k} {{}}", if k == 0 { "" } else { " else " })).collect();
        let _ = write!(
            o,
            "    let cols = {d}::stored_cols_t{j}();\n    assert forall|k: int| 0 <= k < {n} implies #[trigger] cols[k] == k by {{\n        {split}\n    }}\n    \
             let rows = db.tables[{j}];\n    assert forall|i: int| 0 <= i < rows.len() implies #[trigger] rows[i].len() == {n} by {{\n        \
             assert(row_in_table(rows[i], db.schema[{j}]));\n    }}\n    lemma_proj_identity(rows, cols, {n});\n"
        );
    }
    let _ = write!(o, "    assert({d}::stored_relations(db) =~= db.tables);\n}}\n\n");
}

/// The column schema (every table and column of `schema`, no constraint) as executable data, proved equal to
/// `crate::schema::schema_spec()`, its header naming `generator`: an engine crate's `gendb_entry/schema_exec.rs`
/// (generator: the engine entry's identity) and a whole-schema storage crate's `schema_exec.rs`.
pub(super) fn schema_exec_text(schema: &[TableDef], generator: &str) -> String {
    let mut o = String::new();
    let _ = writeln!(o, "// FRAMEWORK FILE, GENERATED by gendb_verification::obligations ({generator}): the column schema as");
    o.push_str(
        "// executable data. Data only (the dataset DDL's tables and columns, as in `schema.rs`); checked by Verus with the\n\
         // crate, so a wrong generation fails verification.\n\
         use vstd::prelude::*;\nuse crate::spec::types::*;\nuse crate::exec::relational::schema::*;\nuse crate::schema::schema_spec;\n\nverus! {\n\n\
         /// `schema_spec()` (the column schema; table id = position) as the interpreter's runtime schema.\n\
         pub fn schema_exec() -> (s: Vec<ETableSchema>)\n    ensures\n        view_schema(s@) == schema_spec(),\n{\n",
    );
    for (i, t) in schema.iter().enumerate() {
        let columns: Vec<String> = t.columns.iter().map(|c| format!("Column {{ ty: {}, nullable: {} }}", sql_type(&c.ty), c.nullable)).collect();
        let _ = writeln!(o, "    // {}", comment_text(&t.name));
        let _ = writeln!(o, "    let t{i} = ETableSchema {{ columns: vec![{}], constraints: Vec::new() }};", columns.join(", "));
        let _ = writeln!(o, "    assert(t{i}.columns@ =~= seq![{}]);", columns.join(", "));
        let _ = writeln!(o, "    assert(view_constraints(t{i}.constraints@) =~= Seq::<Constraint>::empty());");
    }
    let names: Vec<String> = (0..schema.len()).map(|i| format!("t{i}")).collect();
    let _ = writeln!(o, "    let s = vec![{}];", names.join(", "));
    o.push_str("    assert(view_schema(s@) =~= schema_spec());\n    s\n}\n\n} // verus!\n");
    o
}

/// `schema_exec.rs` of a whole-schema storage crate (module `crate::schema_exec`).
pub(super) fn storage_schema_exec_file(schema: &[TableDef]) -> FrameworkSource {
    file(STORAGE_SCHEMA_EXEC_PATH, schema_exec_text(schema, WHOLE_SCHEMA_GENERATOR))
}
