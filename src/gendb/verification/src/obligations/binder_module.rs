//! Generator of `gendb_entry/binder.rs` (v3 candidate and storage crates): the verified binding of the ABI column list (`t0_f0, t0_f1, .., t1_f0, ..`)
//! to the source module's `SourceRef`.
//!
//! `bind_source` decides `gendb_source::source_wf` exactly: the column count and element types, then per table its
//! own row count (field 0's length; a text field 0 gives offsets - 1), every other field of that table of that
//! length, and every text field's offsets well formed. Tables may have different row counts. Anything else is
//! `None`, which the entry reports as `Refused`. The mapping (field `t{j}_f{k}` -> ABI column -> `Column` variant) is
//! the host binding the TCB item `canonical_columns` names.
//!
//! A nullable field's validity `t{j}_v{k}` is the ABI column right after its values: a `Column::Utf8` with no offsets
//! whose bytes are the validity, one per row (`gendb_abi.rs` has no byte-column variant, and a new variant would change
//! the closure of every admitted storage). A text column always has at least one offset, so the two never coincide.
//! Without a nullable field the generated text is the one generated before validity columns existed.

use super::declared::{ColumnKind, DeclaredSource};
use gendb_frontend::translator::comment_text;
use std::fmt::Write as _;

/// `gendb_entry/binder.rs` of `source` for the fixed entry `entry_identity` (the v3 query entry or the storage entry;
/// checked by `DeclaredSource::check_deliverable`: every table delivers a field 0). `identity` names the statement or
/// storage in the header only.
pub(super) fn binder_module(source: &DeclaredSource, identity: &str, entry_identity: &str) -> String {
    // (ABI column position, view field name, what the column carries), in ABI order.
    let fields: Vec<(usize, String, AbiColumn)> = source
        .fields()
        .flat_map(|(j, k, c)| {
            let values = (format!("t{j}_f{k}"), AbiColumn::Values(c.ty.kind()));
            if c.nullable { vec![values, (format!("t{j}_v{k}"), AbiColumn::Validity)] } else { vec![values] }
        })
        .enumerate()
        .map(|(i, (name, column))| (i, name, column))
        .collect();
    let mut o = String::new();
    let _ = writeln!(o, "// FRAMEWORK FILE, GENERATED by gendb_verification::obligations ({entry_identity}): binds the ABI");
    let _ = writeln!(o, "// columns to the source declaration's SourceRef (gendb_source) for {identity}.");
    for (j, t) in source.tables.iter().enumerate() {
        let listed = t
            .columns
            .iter()
            .enumerate()
            .map(|(k, c)| {
                let validity = if c.nullable { format!(", t{j}_v{k} validity Utf8 (no offsets)") } else { String::new() };
                format!("t{j}_f{k} {} {}{validity}", comment_text(&c.name), c.ty.kind().abi_variant())
            })
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(o, "// Table t{j} = {}: {listed}.", comment_text(&t.name));
    }
    o.push_str("use vstd::prelude::*;\nuse crate::gendb_abi::Column;\n");
    o.push_str("use crate::gendb_source::{source_wf, SourceRef, SourceView, TextCol, TextView};\n");
    o.push_str("use super::work::text_offsets_ok;\n\nverus! {\n\n");
    write_column_source(&mut o, &fields);
    write_bind_source(&mut o, source, &fields);
    o.push_str("} // verus!\n");
    o
}

/// What one ABI column of the declaration carries.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum AbiColumn {
    /// The values of a field, in its element kind's variant.
    Values(ColumnKind),
    /// The validity of the nullable field before it: `Column::Utf8` with no offsets, the bytes one per row.
    Validity,
}

/// `column_source`: the source view the columns carry, if they are well formed (with a validity column,
/// `is_validity_column` first, which names that shape).
fn write_column_source(o: &mut String, fields: &[(usize, String, AbiColumn)]) {
    if fields.iter().any(|(_, _, column)| *column == AbiColumn::Validity) {
        o.push_str(
            "/// A validity column: the bytes of a `Column::Utf8` with no offsets, one per row (0: NULL). A text column always has\n\
             /// at least one offset, so the two never coincide.\n\
             pub open spec fn is_validity_column(c: Column) -> bool {\n    c is Utf8 && c->Utf8_offsets@.len() == 0\n}\n\n",
        );
    }
    o.push_str("/// The source view carried by `columns` if count, element types, per-table row counts and text offsets match.\n");
    o.push_str("pub open spec fn column_source(columns: Seq<Column>) -> Option<SourceView> {\n");
    let _ = write!(o, "    if columns.len() == {}", fields.len());
    for (i, _, column) in fields {
        match column {
            AbiColumn::Values(kind) => {
                let _ = write!(o, " && columns[{i}] is {}", kind.abi_variant());
            }
            AbiColumn::Validity => {
                let _ = write!(o, " && is_validity_column(columns[{i}])");
            }
        }
    }
    let view = fields
        .iter()
        .map(|(i, name, column)| match column {
            AbiColumn::Values(ColumnKind::Utf8) => format!("{name}: TextView {{ offsets: columns[{i}]->Utf8_offsets@, bytes: columns[{i}]->Utf8_bytes@ }}"),
            AbiColumn::Values(k) => format!("{name}: columns[{i}]->{}_0@", k.abi_variant()),
            AbiColumn::Validity => format!("{name}: columns[{i}]->Utf8_bytes@"),
        })
        .collect::<Vec<_>>()
        .join(", ");
    let _ = write!(o, " {{\n        let v = SourceView {{ {view} }};\n        if source_wf(v) {{ Some(v) }} else {{ None }}\n    }} else {{\n        None\n    }}\n}}\n\n");
}

/// `bind_source`: the executable decision of `column_source`.
fn write_bind_source(o: &mut String, source: &DeclaredSource, fields: &[(usize, String, AbiColumn)]) {
    o.push_str("pub(super) fn bind_source(columns: &[Column]) -> (r: Option<SourceRef>)\n");
    o.push_str("    ensures\n        match r {\n            Some(s) => column_source(columns@) == Some(s@) && source_wf(s@),\n");
    o.push_str("            None => column_source(columns@) is None,\n        },\n{\n");
    let _ = writeln!(o, "    if columns.len() != {} {{\n        return None;\n    }}", fields.len());
    for (i, name, column) in fields {
        match column {
            AbiColumn::Values(ColumnKind::Utf8) => {
                let _ = writeln!(
                    o,
                    "    let {name} = match &columns[{i}] {{ Column::Utf8 {{ offsets, bytes }} => TextCol {{ offsets: *offsets, bytes: *bytes }}, _ => return None }};"
                );
            }
            AbiColumn::Values(k) => {
                let _ = writeln!(o, "    let {name} = match &columns[{i}] {{ Column::{}(s) => *s, _ => return None }};", k.abi_variant());
            }
            AbiColumn::Validity => {
                let _ = writeln!(
                    o,
                    "    let {name}: &'static [u8] = match &columns[{i}] {{\n        Column::Utf8 {{ offsets, bytes }} => {{\n            if offsets.len() != 0 {{\n                return None;\n            }}\n            *bytes\n        }},\n        _ => return None,\n    }};"
                );
            }
        }
    }
    let names = fields.iter().map(|(_, name, _)| name.as_str()).collect::<Vec<_>>().join(", ");
    let _ = writeln!(o, "    let s = SourceRef {{ {names} }};");
    o.push_str("    let ghost v = s@;\n");
    o.push_str("    assert(column_source(columns@) == if source_wf(v) { Some(v) } else { None::<SourceView> });\n");
    for (j, t) in source.tables.iter().enumerate() {
        // Row count of table j from its field 0.
        if t.columns[0].ty.kind() == ColumnKind::Utf8 {
            let _ = writeln!(o, "    if s.t{j}_f0.offsets.len() == 0 {{\n        return None;\n    }}");
            let _ = writeln!(o, "    let n{j}: usize = s.t{j}_f0.offsets.len() - 1;");
        } else {
            let _ = writeln!(o, "    let n{j}: usize = s.t{j}_f0.len();");
        }
        for (k, c) in t.columns.iter().enumerate() {
            match c.ty.kind() {
                ColumnKind::Utf8 => {
                    let _ = writeln!(o, "    if !text_offsets_ok(&s.t{j}_f{k}, n{j}) {{\n        return None;\n    }}");
                }
                _ if k == 0 => {}
                _ => {
                    let _ = writeln!(o, "    if s.t{j}_f{k}.len() != n{j} {{\n        return None;\n    }}");
                }
            }
            if c.nullable {
                let _ = writeln!(o, "    if s.t{j}_v{k}.len() != n{j} {{\n        return None;\n    }}");
            }
        }
    }
    o.push_str("    Some(s)\n}\n\n");
}
