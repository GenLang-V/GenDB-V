//! Generator of version 0 of the general engine (identity `gendb-interpreter-engine-v0`): the
//! engine `agent/` sources that answer every supported statement with SQLSpec's verified
//! interpreter over the generated flat storages of every table.
//!
//! The generated `agent/mod.rs` is the same text for every schema. It names no table, column or storage: it reads the
//! database through the engine crate's generated flat access module (`crate::flat_tables`, `obligations::flat_tables`:
//! `materialize_database`), runs `exec_ordered`, maps its outcome (rows, the SQL error, `Capacity` outside the
//! executable domain) and proves `answer_meets` by the uniqueness of the bound database (`lemma_flat_database_unique`:
//! every table is flat-stored and the flat storages are lossless). The schema enters only through the generated
//! framework files, so the generator's one input check is that every table of the schema has a generated flat storage
//! among the uses ([`interpreter_engine`]).
//!
//! Version 0 is framework code, not an author's: it is frozen, verified and admitted through the normal engine route
//! (whole crate, `--no-cheating`, the general line's source rules, which allow the interpreter). Infeasible at scale:
//! every call materializes every table, and the interpreter materializes every FROM product, re-runs subqueries per row
//! and groups and sorts in quadratic time.

use super::flat_tables::generated_flat_table;
use super::query_crate::StorageUse;
use super::AssemblyError;
use crate::verus::FrameworkSource;
use gendb_frontend::ast::TableDef;
use std::collections::BTreeSet;

/// Identity of this generator (version 0 of the general engine), recorded with its frozen engine.
pub const INTERPRETER_ENGINE_GENERATOR: &str = "gendb-interpreter-engine-v0";

/// The author files of version 0 (`agent/mod.rs`, relative to the crate's `src/`) for an engine crate over `schema`
/// reading `uses`. Refused (`Storage`, reason `interpreter_engine_needs_flat_tables`) unless every table of the schema
/// has a generated flat storage among the uses; other uses may be present and are not read.
pub fn interpreter_engine(schema: &[TableDef], uses: &[StorageUse<'_>]) -> Result<Vec<FrameworkSource>, AssemblyError> {
    let flat: BTreeSet<usize> = uses.iter().filter_map(|u| generated_flat_table(schema, u)).collect();
    if let Some((_, table)) = schema.iter().enumerate().find(|(id, _)| !flat.contains(id)) {
        return Err(AssemblyError::Storage(format!(
            "interpreter_engine_needs_flat_tables: version 0 reads every table from its generated flat storage, and table {} has none among the engine's storage uses",
            table.name
        )));
    }
    Ok(vec![FrameworkSource { path: "agent/mod.rs".into(), text: INTERPRETER_ENGINE_AGENT.into() }])
}

/// `agent/mod.rs` of version 0 (the same text for every schema).
const INTERPRETER_ENGINE_AGENT: &str = r#"//! Version 0 of the general engine (generated by GenDB, gendb-interpreter-engine-v0; framework code, not an author's).
//!
//! It reads every table through the generated flat access (`crate::flat_tables::materialize_database`) and answers
//! every supported statement with SQLSpec's verified interpreter (`exec_ordered`). Its answer is the canonical
//! denotation, so its proof is the interpreter's theorem plus "the materialized tables are the bound database": every
//! table is flat-stored and each flat storage is lossless, so every database bound to the parts is the one
//! materialized (`lemma_flat_database_unique`). It names no table or column. Infeasible at scale: every call
//! materializes every table, and the interpreter materializes every FROM product, re-runs subqueries per row and
//! groups and sorts in quadratic time; the engine's workers are not used.
use vstd::prelude::*;
use crate::gendb_entry::{answer_meets, bound_db, outcome_ok, stores_ready, supported, Answer};
use crate::gendb_entry::parallel::{Dispatch, MAX_WORKERS};
use crate::gendb_entry::runtime::QueryError;
use crate::gendb_entry::stores::Stores;
use crate::exec::ast::{view_ordered, EOrderedQuery};
use crate::exec::relational::schema::{lemma_db_wf_ts_ok, view_rows};
use crate::exec::relational::entry::exec_ordered;
use crate::bridge::order::lemma_denote_top_ok;
use crate::flat_tables::{lemma_flat_database_unique, materialize_database};
use crate::spec::value::Database;

verus! {

/// The engine: every supported statement over the stored tables, answered by the verified interpreter.
pub fn engine(stores: &mut Stores, q: &EOrderedQuery, workers: usize, dispatch: &mut Dispatch) -> (r: Result<Answer, QueryError>)
    requires
        stores_ready(old(stores)@),
        supported(view_ordered(*q)),
        1 <= workers <= MAX_WORKERS,
    ensures
        answer_meets(old(stores)@, view_ordered(*q), r),
{
    let ghost sv = stores@;
    let ghost db = choose|db: Database| bound_db(sv, db);
    let edb = materialize_database(stores, Ghost(db));
    proof {
        lemma_db_wf_ts_ok(db);
        lemma_denote_top_ok(db, view_ordered(*q));
    }
    let r: Result<Answer, QueryError> = match exec_ordered(&edb, q) {
        Ok(Ok(rows)) => {
            proof {
                assert(crate::link::query::view_rows(rows@) =~= view_rows(rows@));
            }
            Ok(Answer::Rows(rows))
        },
        Ok(Err(e)) => Ok(Answer::SqlError(e)),
        Err(_) => Ok(Answer::Capacity),
    };
    proof {
        assert forall|other: Database| #[trigger] bound_db(sv, other) implies outcome_ok(other, view_ordered(*q), r) by {
            lemma_flat_database_unique(sv, db, other);
        }
    }
    r
}

} // verus!
"#;
