//! Files that storage crates and query crates share, and the pieces both assemblies use: the SQLSpec
//! library, the schema module, the declared-constraints module, a storage's module and declaration, the fixed entry
//! submodules with the stored-parts read handle, crate roots and the trusted shim.

use super::declaration_module::declaration_module;
use super::declared::DeclaredSource;
use super::candidate::ENTRY_SUBMODULE_FILES;
use super::storage_crate::StorageName;
use super::AssemblyError;
use crate::verus::FrameworkSource;
use gendb_frontend::ast::TableDef;
use gendb_frontend::translator::{emit_column_schema_module, emit_constraints_module, EmitOptions};
use gendb_registry::STORED_PARTS_SOURCE;
use gendb_sqlspec::library::{self, CANDIDATE_MODULES};

pub(super) fn file(path: impl Into<String>, text: impl Into<String>) -> FrameworkSource {
    FrameworkSource { path: path.into(), text: text.into() }
}

/// The SQLSpec library files every crate copies (semantics, interpreter, bridge, link), in logical-path order.
pub(super) fn library_files() -> impl Iterator<Item = FrameworkSource> {
    library::module_files(CANDIDATE_MODULES).into_iter().map(|f| file(f.path, f.text))
}

/// `schema.rs`: the column schema of the dataset, independent of any statement and of any declared constraint.
pub(super) fn schema_file(schema: &[TableDef]) -> Result<FrameworkSource, AssemblyError> {
    let text = emit_column_schema_module(schema, &EmitOptions::candidate()).map_err(AssemblyError::Emit)?;
    Ok(file("schema.rs", text))
}

/// `gendb_constraints.rs`: the declared integrity constraints of the schema over its column schema (`declared_schema`,
/// `declared_db`, `lemma_declared_schema`); `None` when no table declares a constraint. Statement independent.
pub(super) fn constraints_file(schema: &[TableDef]) -> Result<Option<FrameworkSource>, AssemblyError> {
    let text = emit_constraints_module(schema, &EmitOptions::candidate()).map_err(AssemblyError::Emit)?;
    Ok(text.map(|text| file(CONSTRAINTS_MODULE_FILE, text)))
}

/// The run's declared integrity constraints as every crate and record states them: the text of the generated
/// `gendb_constraints.rs` of the dataset schema `schema` (a document's `tables`), `None` when no table declares one.
/// Storage tools compare its digest with a storage package's `assumed_constraints`.
pub fn declared_constraints_text(schema: &[TableDef]) -> Result<Option<String>, AssemblyError> {
    Ok(constraints_file(schema)?.map(|f| f.text))
}

/// The path of the declared-constraints module, relative to `src/` (module `crate::gendb_constraints`).
pub(super) const CONSTRAINTS_MODULE_FILE: &str = gendb_artifacts::verus::CONSTRAINTS_MODULE_PATH;

/// The column count of every table of the schema (the generators' bound checks).
pub(super) fn schema_widths(schema: &[TableDef]) -> Vec<usize> {
    schema.iter().map(|t| t.columns.len()).collect()
}

/// `stores/<name>/mod.rs` and `stores/<name>/declaration.rs` of one storage (checked by
/// `DeclaredSource::check_deliverable` against `widths`).
pub(super) fn storage_module_files(name: &StorageName, declaration: &DeclaredSource, widths: &[usize]) -> [FrameworkSource; 2] {
    let root = format!(
        "// FRAMEWORK FILE, GENERATED by gendb_verification::obligations: storage `{name}` (its declaration and the author's\n\
         // interface). The same text in the storage crate and in every query crate that reads the storage.\n\
         pub mod declaration;\npub mod interface;\n"
    );
    [
        file(format!("stores/{name}/mod.rs"), root),
        file(format!("stores/{name}/declaration.rs"), declaration_module(name, declaration, widths)),
    ]
}

/// `stores.rs`: the storage modules a crate carries.
pub(super) fn stores_list_file(names: &[&StorageName]) -> FrameworkSource {
    let mut text = String::from("// FRAMEWORK FILE, GENERATED by gendb_verification::obligations: the storages this crate carries.\n");
    for name in names {
        text.push_str(&format!("pub mod {name};\n"));
    }
    file("stores.rs", text)
}

/// The fixed submodules of `crate::gendb_entry` both kinds carry: the v3 submodules and the stored-parts read handle.
pub(super) fn shared_entry_files() -> impl Iterator<Item = FrameworkSource> {
    ENTRY_SUBMODULE_FILES.iter().map(|(path, text)| file(*path, *text)).chain([file("gendb_entry/stored.rs", STORED_PARTS_SOURCE)])
}

/// A crate root: `header`, the library's crate attributes and module declarations, then `modules` (in order).
pub(super) fn crate_root(header: &str, modules: &[&str]) -> FrameworkSource {
    let mut text = format!("{header}\n");
    for attribute in library::crate_attributes() {
        text.push_str(attribute);
        text.push('\n');
    }
    text.push_str(&library::module_declarations(CANDIDATE_MODULES));
    for module in modules {
        text.push_str(&format!("pub mod {module};\n"));
    }
    file("lib.rs", text)
}

/// `files` of a storage or query crate with the trusted C ABI shim `shim` (`gendb_shim.rs`, outside `verus!`, the
/// runtime's text for the crate kind) added and declared, private, in the crate root. The verified crate files do not
/// depend on it.
pub fn with_trusted_shim(mut files: Vec<FrameworkSource>, shim: &str) -> Vec<FrameworkSource> {
    if let Some(root) = files.iter_mut().find(|f| f.path == "lib.rs") {
        root.text.push_str("mod gendb_shim;\n");
    }
    files.push(file("gendb_shim.rs", shim));
    files
}
