//! Source files of a reference evaluator crate for one translated statement.
//!
//! Layout (`src/` of the crate): `lib.rs` (generated root), the library modules [`EVALUATOR_MODULES`] at their
//! logical paths, `query.rs` (the translated statement, `gendb_frontend::translator::emit_query_module`),
//! `query_schema.rs` ([`schema_module`]), `abi.rs` (verified entry) and `shim.rs` (trusted C ABI shim, the only
//! file the refusal scanner does not read).

use crate::library::{self, EVALUATOR_MODULES};
use gendb_frontend::ast::{AstDocument, ConstraintDef};
use gendb_frontend::translator::{check_prefix, comment_text, emit_query_module, exec_chain, nat_seq, spec_constraint, sql_type, EmitError, EmitOptions};
use std::fmt::Write as _;

/// Version of the evaluator crate layout and its generated files, recorded with every build. v2: the library comes
/// from the compile-time embedded SQLSpec bundle; v1 (the earlier version) read `tcb/sql-semantics/verus` at run time.
pub const CRATE_IDENTITY: &str = "gendb-sql-crate-v2";
/// The verified entry points `abi_run` / `abi_echo` (physical `sqlspec/interpreter/host/abi.rs`).
pub const ENTRY_FILE: &str = "abi.rs";
pub const ENTRY_SOURCE: &str = include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/interpreter/host/abi.rs"));
/// The trusted C ABI shim (physical `sqlspec/interpreter/host/shim.rs`).
pub const SHIM_FILE: &str = "shim.rs";
pub const SHIM_SOURCE: &str = include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/interpreter/host/shim.rs"));
/// Files of an evaluator crate the refusal scanner does not read (trusted FFI code the refusal list forbids).
pub const UNSCANNED_TRUSTED_FILES: &[&str] = &[SHIM_FILE];

/// One file of a crate, relative to its `src/`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SourceFile {
    pub path: String,
    pub text: String,
}

/// Every source file of the evaluator crate of `doc`, sorted by path. `Err` is the emitter's refusal.
pub fn crate_files(doc: &AstDocument) -> Result<Vec<SourceFile>, EmitError> {
    let query = emit_query_module(doc, &EmitOptions::default())?;
    let schema = schema_module(doc)?;
    let mut files: Vec<SourceFile> =
        library::module_files(EVALUATOR_MODULES).into_iter().map(|f| SourceFile { path: f.path.into(), text: f.text.into() }).collect();
    files.push(SourceFile { path: library::ROOT_PATH.into(), text: crate_root() });
    files.push(SourceFile { path: "query.rs".into(), text: query });
    files.push(SourceFile { path: "query_schema.rs".into(), text: schema });
    files.push(SourceFile { path: ENTRY_FILE.into(), text: ENTRY_SOURCE.into() });
    files.push(SourceFile { path: SHIM_FILE.into(), text: SHIM_SOURCE.into() });
    files.sort_by(|a, b| a.path.cmp(&b.path));
    Ok(files)
}

/// `lib.rs` of an evaluator crate: the library root's attributes, the evaluator's library modules, then the
/// statement modules, the entry and the shim.
pub fn crate_root() -> String {
    let mut o = String::new();
    let _ = writeln!(o, "// FRAMEWORK FILE, GENERATED by gendb_sqlspec::evaluator ({CRATE_IDENTITY}): reference evaluator crate root.");
    for attribute in library::crate_attributes() {
        o.push_str(attribute);
        o.push('\n');
    }
    o.push_str(&library::module_declarations(EVALUATOR_MODULES));
    o.push_str("pub mod query;\npub mod query_schema;\npub mod abi;\nmod shim;\n");
    o
}

/// `query_schema.rs`: the statement's schema as executable data, proved equal to the emitted `schema_spec`:
/// columns, keys, foreign keys and CHECK predicates (each CHECK built by the translator's exec chain, one view
/// step per node). Names follow the translator's `schema_spec` (`check_prefix`, `spec_constraint`).
pub fn schema_module(doc: &AstDocument) -> Result<String, EmitError> {
    let mut o = String::new();
    let _ = writeln!(o, "// FRAMEWORK FILE, GENERATED by gendb_sqlspec::evaluator ({CRATE_IDENTITY}): executable schema.");
    o.push_str("use vstd::prelude::*;\nuse crate::spec::types::*;\nuse crate::spec::int::*;\nuse crate::spec::scalar::*;\nuse crate::spec::ast::*;\n");
    o.push_str("use crate::exec::ast::*;\nuse crate::exec::relational::schema::*;\nuse crate::query::schema_spec;\n\nverus! {\n\n");
    o.push_str("/// The schema the query was resolved against (table id = position), as the evaluator's runtime schema.\n");
    o.push_str("pub fn schema_exec() -> (s: Vec<ETableSchema>)\n    ensures view_schema(s@) == schema_spec(),\n{\n");
    for (i, t) in doc.tables.iter().enumerate() {
        let cols: Vec<String> = t.columns.iter().map(|c| format!("Column {{ ty: {}, nullable: {} }}", sql_type(&c.ty), c.nullable)).collect();
        let _ = writeln!(o, "    // {}", comment_text(&t.name));
        let mut exec_constraints = Vec::new();
        let mut spec_constraints = Vec::new();
        for (k, c) in t.constraints.iter().enumerate() {
            let v = format!("t{i}_c{k}");
            match c {
                ConstraintDef::Key { primary, columns, nulls_distinct, .. } => {
                    column_list(&mut o, &format!("{v}_cols"), columns);
                    let _ = writeln!(o, "    let {v} = EConstraint::Key {{ cols: {v}_cols, primary: {primary}, nulls_distinct: {nulls_distinct} }};");
                }
                ConstraintDef::ForeignKey { columns, table, ref_columns, match_full, .. } => {
                    column_list(&mut o, &format!("{v}_cols"), columns);
                    column_list(&mut o, &format!("{v}_ref"), ref_columns);
                    let _ = writeln!(
                        o,
                        "    let {v} = EConstraint::ForeignKey {{ cols: {v}_cols, table: {table}usize, ref_cols: {v}_ref, match_full: {match_full} }};"
                    );
                }
                ConstraintDef::Check { nodes, root, .. } => {
                    let prefix = format!("c{i}_{k}_");
                    exec_chain(&mut o, nodes, &prefix)?;
                    let _ = writeln!(o, "    let {v} = EConstraint::Check({prefix}e{root});");
                }
            }
            exec_constraints.push(v);
            spec_constraints.push(spec_constraint(c, &check_prefix(i, k, "g")));
        }
        let _ = writeln!(o, "    let t{i} = ETableSchema {{ columns: vec![{}], constraints: vec![{}] }};", cols.join(", "), exec_constraints.join(", "));
        let _ = writeln!(o, "    assert(t{i}.columns@ =~= seq![{}]);", cols.join(", "));
        let _ = writeln!(o, "    assert(view_constraints(t{i}.constraints@) =~= seq![{}]);", spec_constraints.join(", "));
    }
    let names: Vec<String> = (0..doc.tables.len()).map(|i| format!("t{i}")).collect();
    let _ = writeln!(o, "    let s = vec![{}];", names.join(", "));
    let _ = writeln!(o, "    assert(view_schema(s@) =~= schema_spec());");
    o.push_str("    s\n}\n\n} // verus!\n");
    Ok(o)
}

/// `let <name>: Vec<usize> = vec![..];` with its view equality to the spec column list.
fn column_list(o: &mut String, name: &str, columns: &[u64]) {
    let items = columns.iter().map(|c| format!("{c}usize")).collect::<Vec<_>>().join(", ");
    let _ = writeln!(o, "    let {name}: Vec<usize> = vec![{items}];");
    let _ = writeln!(o, "    assert(view_cols({name}@) =~= {});", nat_seq(columns));
}
